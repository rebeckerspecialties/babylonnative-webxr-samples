"""Regenerate the texture-video oracle from the pinned VP8 source, not from the renderer."""
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
clip = root / "third_party/webxr-samples/media/video/bbb-sunflower-540p2-1min.webm"
samples = []
for i in range(19):
    # Exact PTS in this 30 fps clip. Keep the full-res texel centers; do not box-filter.
    data = subprocess.check_output(["ffmpeg", "-loglevel", "error", "-ss", str(12+i/6), "-i", str(clip),
                                    "-frames:v", "1", "-pix_fmt", "rgb24", "-f", "rawvideo", "-"])
    assert len(data) == 960*1080*3
    colors = bytearray()
    for y in range(24):
        for x in range(24):
            start = (int((y+.5)*1080/24)*960+int((x+.5)*960/24))*3
            colors.extend(data[start:start+3])
    samples.append(colors.hex())
(root / "videoReference.mjs").write_text("// Generated by tools/video-reference.py from the packaged stereo clip.\n"
    + "export const referenceRGB = " + json.dumps(samples, indent=2) + ";\n")
